def verify_builder_snippet(
    language: str,
    code_snippet: str,
    dependencies_used: List[str]
) -> Dict[str, Any]:
    """
    Unified validation entrypoint for AI Builder Agent output.
    Checks:
    1. Zero external dependencies constraint (dependencies_used MUST be empty []).
    2. Non-empty implementation (at least 15 chars).
    3. Ecosystem-specific syntax validation.
    """
    if not code_snippet or len(code_snippet.strip()) < 15:
        return {
            "syntax_valid": False,
            "zero_dependencies_valid": len(dependencies_used) == 0,
            "error": "Code snippet is empty or excessively short (<15 characters)"
        }

    # Strict Zero-Dependency Check
    if dependencies_used and len(dependencies_used) > 0:
        return {
            "syntax_valid": False,
            "zero_dependencies_valid": False,
            "error": f"Violation: Builder declared external dependencies: {dependencies_used}"
        }

    lang = (language or "python").lower().strip()
    is_valid = False
    message = "Unknown language"

    if lang == "python":
        is_valid, message = verify_python_syntax(code_snippet)
    elif lang in ["typescript", "javascript", "ts", "js"]:
        is_valid, message = verify_typescript_syntax(code_snippet)
    elif lang == "rust":
        is_valid, message = verify_rust_syntax(code_snippet)
    elif lang == "go":
        is_valid, message = verify_go_syntax(code_snippet)
    elif lang == "java":
        is_valid, message = verify_java_syntax(code_snippet)
    else:
        # Fallback to general balanced bracket check
        is_valid, message = verify_typescript_syntax(code_snippet)

    return {
        "language": lang,
        "syntax_valid": is_valid,
        "zero_dependencies_valid": True,
        "details": message
    }


