"""
verify_syntax.py
----------------
Automated syntax and safety validator for zero-dependency code snippets
generated by the BuildOrBorrow AI Builder Agent.
Supports all 5 ecosystem target languages:
- Python (PyPI)
- TypeScript / JavaScript (NPM)
- Rust (Cargo)
- Go (Go)
- Java (Maven)
"""

import ast
import re
from typing import Tuple, List, Dict, Any


def verify_python_syntax(code: str) -> Tuple[bool, str]:
    """Validates Python syntax using the standard library ast parser."""
    try:
        ast.parse(code)
        return True, "Valid Python AST syntax"
    except SyntaxError as e:
        return False, f"Python SyntaxError at line {e.lineno}: {e.msg}"


def verify_typescript_syntax(code: str) -> Tuple[bool, str]:
    """Validates TypeScript / JavaScript structural syntax, bracket balancing, and token integrity."""
    brackets = {"(": ")", "[": "]", "{": "}"}
    stack = []
    
    # Strip comments and string literals to prevent bracket false positives
    cleaned = re.sub(r"/\*[\s\S]*?\*/", "", code)
    cleaned = re.sub(r"//.*", "", cleaned)
    cleaned = re.sub(r"'(?:\\.|[^'])*'", "''", cleaned)
    cleaned = re.sub(r'"(?:\\.|[^"])*"', '""', cleaned)
    cleaned = re.sub(r"`(?:\\.|[^`])*`", "``", cleaned)

    for char in cleaned:
        if char in brackets:
            stack.append(char)
        elif char in brackets.values():
            if not stack or brackets[stack.pop()] != char:
                return False, f"Unbalanced bracket mismatch in TypeScript code: '{char}'"

    if stack:
        return False, f"Unclosed opening bracket in TypeScript code: '{stack[-1]}'"

    # Basic structural check for function, export, or variable declaration
    has_code = any(keyword in code for keyword in ["function", "const", "let", "export", "return", "=>", "class"])
    if not has_code:
        return False, "TypeScript snippet lacks executable statements or definitions"

    return True, "Valid TypeScript structural syntax and balanced brackets"


